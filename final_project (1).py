# 1. Load the clean dataset from Step 2
# ------------------------------------------------------------------------------
file_name = 'alzheimer_dataset_clean.csv'

try:
    df = pd.read_csv(file_name)
    print(f"📂 Loaded balanced dataset: {len(df)} compounds.")

    # 2. Generate Morgan Fingerprints (ECFP4 equivalent)
    # ------------------------------------------------------------------------------
    print("⚗️ Calculating 1024-bit Fingerprints (this takes a moment)...")

    def get_fingerprint_modern(smiles):
        try:
            mol = Chem.MolFromSmiles(str(smiles))
            if mol:
                # Modern generator (Radius 2, 1024 bits)
                gen = rdFingerprintGenerator.GetMorganGenerator(radius=2, fpSize=1024)
                return gen.GetFingerprintAsNumPy(mol)
            return None
        except:
            return None

    # Apply transformation to the whole column
    fp_series = df['Smiles'].apply(get_fingerprint_modern)

    # 3. Create Feature Matrix (X) and Target Vector (y)
    # ------------------------------------------------------------------------------
    # Remove any molecules that failed calculation (sanity check) (maybe because smiles text were wrong)
    valid_idx = fp_series.notna()

    # X = The Chemistry (Features) -> The input for the AI (transforming the fingerprints into a mathematical matrix)
    X = np.stack(fp_series[valid_idx].values)

    # y = The Activity (Class: 0 or 1) -> The answer key
    y = df.loc[valid_idx, 'Class'].values

    print(f"✅ Feature Matrix (X) Shape: {X.shape} (Rows, Features)")
    print(f"✅ Target Vector (y) Shape: {y.shape}")
    print("🎉 Step 3 Complete. Data is ready for Machine Learning.")

except FileNotFoundError:
    print("❌ Error: File not found. Please run Step 2 first.")

