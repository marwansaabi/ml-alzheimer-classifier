# ==============================================================================
# STEP 1: DATA LOADING AND FILTRATION
# ==============================================================================
# Objective: Load raw ChEMBL data and retain only valid bioactivity measurements.

import pandas as pd
import numpy as np

# 1. Load the dataset
# ------------------------------------------------------------------------------
file_name = '/content/datos_alzheimer.csv' # Ensure this matches your uploaded file
print(f"📂 Loading raw data: {file_name}...")

try:
    # Try reading with semicolon (standard for ChEMBL)
    df = pd.read_csv(file_name, sep=';')

    # Fallback to comma if necessary
    if 'Smiles' not in df.columns:
        df = pd.read_csv(file_name, sep=',')

    print(f"   Total raw entries: {len(df)}")

    # 2. Filter for Quality (IC50 & nM)
    # ------------------------------------------------------------------------------
    # We only keep the 5 essential columns for the AI
    df = df[['Molecule ChEMBL ID', 'Smiles', 'Standard Value', 'Standard Units', 'Standard Type']]

    # Filter A: Keep only IC50 assays (Potency)
    df = df[df['Standard Type'] == 'IC50']

    # Filter B: Keep only Nanomolar units (to ensure comparability)
    df = df[df['Standard Units'] == 'nM'] # We eliminated 1265 rows that had no units (ambiguous data), and only 71 rows with different units.

    # Filter C: Remove rows with missing chemical structure or value
    df = df.dropna(subset=['Smiles', 'Standard Value'])

    # Technical Fix: Convert text numbers (e.g., "1,500") to float (1500.0)
    if df['Standard Value'].dtype == object:
         df['Standard Value'] = df['Standard Value'].astype(str).str.replace(',', '.').astype(float)

    print(f"✅ Valid biological data points (IC50 in nM): {len(df)}")
    print("Step 1 Complete. Proceed to Step 2.")

except Exception as e:
    print(f"❌ Error: {e}")

# ==============================================================================
# STEP 2: CLASSIFICATION AND CLASS BALANCING
# ==============================================================================
# Objective: Label compounds based on potency and balance the dataset.

# 1. Define Scientific Criteria (Labeling)
# ------------------------------------------------------------------------------
# Active (Class 1): IC50 <= 1000 nM (High Potency/Active)
# Inactive (Class 0): IC50 >= 10000 nM (Low Potency/Inactive)
# Gap (Dropped): 1000 - 10000 nM (Removed to increase model robustnes)

def classify_compound(value):
    if value <= 1000:
        return 1 # Active
    elif value >= 10000:
        return 0 # Inactive
    else:
        return -1 # Intermediate/Grey Zone

print("🧪 Applying classification criteria...")
df['Class'] = df['Standard Value'].apply(classify_compound)

# Remove the intermediate zone (-1)
df_clean = df[df['Class'] != -1].copy()

# 2. Class Balancing (Undersampling)
# ------------------------------------------------------------------------------
# We ensure the model sees an equal number of Active and Inactive examples.

actives = df_clean[df_clean['Class'] == 1]
inactives = df_clean[df_clean['Class'] == 0]

print(f"   Counts before balancing: Actives={len(actives)} | Inactives={len(inactives)}")

# Find the size of the minority class
n_samples = min(len(actives), len(inactives))

# Randomly sample from both groups to match sizes
df_balanced = pd.concat([
    actives.sample(n_samples, random_state=42),
    inactives.sample(n_samples, random_state=42)
])

# 3. Save Final Clean Dataset
# ------------------------------------------------------------------------------
output_file = 'alzheimer_dataset_clean.csv'
df_balanced.to_csv(output_file, index=False)

print(f"\n⚖️ FINAL BALANCED DATASET: {len(df_balanced)} compounds ({n_samples} per class)")
print(f"🎉 Success! Clean file saved as '{output_file}'.")

